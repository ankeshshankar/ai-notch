import AppKit

/// The pasteboard's contents, every item and every type, so the clipboard can be put back after
/// dictation borrowed it.
public struct PasteboardSnapshot {
    struct Item { var entries: [(type: NSPasteboard.PasteboardType, data: Data)] }
    var items: [Item]

    public var itemCount: Int { items.count }

    public static func capture(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            Item(entries: item.types.compactMap { type in item.data(forType: type).map { (type, $0) } })
        }
        return PasteboardSnapshot(items: items)
    }

    /// Puts the contents back. An empty snapshot clears the board.
    public func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { item -> NSPasteboardItem in
            let new = NSPasteboardItem()
            for entry in item.entries { new.setData(entry.data, forType: entry.type) }
            return new
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}

/// Puts dictated text on the pasteboard for a paste and restores the clipboard after.
public struct PasteboardLoan {
    public let snapshot: PasteboardSnapshot
    /// The pasteboard's change count right after the text went on: if it differs later, the user
    /// (or an app) has put something else there and the old contents are not forced back.
    public let changeCount: Int
    let pasteboard: NSPasteboard

    /// Marks the text so clipboard managers skip it (nspasteboard.org conventions).
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let auto = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public static func lend(text: String, on pasteboard: NSPasteboard = .general) -> PasteboardLoan {
        let snapshot = PasteboardSnapshot.capture(pasteboard)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transient)
        item.setData(Data(), forType: auto)
        pasteboard.writeObjects([item])
        return PasteboardLoan(snapshot: snapshot, changeCount: pasteboard.changeCount, pasteboard: pasteboard)
    }

    /// Restores the clipboard unless something else has written to it since. True when restored.
    @discardableResult
    public func giveBack() -> Bool {
        guard pasteboard.changeCount == changeCount else { return false }
        snapshot.restore(to: pasteboard)
        return true
    }
}
